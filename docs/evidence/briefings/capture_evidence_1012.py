#!/usr/bin/env python3
"""Capture the real stdout of every verification step into committed evidence.

Addresses ADV-12176-1 and ADV-12176-2: the pass/fail, URL-liveness and
test-result claims must be inspectable artifacts, not a prose assertion in a
governance note.

Writes:
  docs/evidence/briefings/verification-2026-10-12.txt   (structure checks)
  docs/evidence/briefings/test-results-2026-10-12.txt    (test suite stdout)
  docs/evidence/briefings/url-check-2026-10-12.txt       (live HTTP codes)
  docs/evidence/briefings/claim-sources-2026-10-12.tsv   (claim -> source map)
"""
import os
import re
import subprocess
import sys
from pathlib import Path

DATE = "2026-10-12"
HOME = Path.home()
OUT = HOME / ".hermes" / "cron" / "output"
REPO = HOME / "hermes-cortex"
EVID = REPO / "docs" / "evidence" / "briefings"
VENV_PY = str(OUT / ".venv-brief" / "bin" / "python")
BASE = OUT / ("sustainability-briefing-%s" % DATE)


def run(argv, cwd=None, timeout=300):
    return subprocess.run(argv, cwd=cwd, capture_output=True, text=True,
                          timeout=timeout)


def sanitize(text: str) -> str:
    """Replace absolute home paths with ~ so committed evidence is
    path-neutral (the secret-leak detector flags /home/<user>/ literals)."""
    home = str(Path.home())
    return text.replace(home + "/", "~/")


def banner(title, argv, res, outfile):
    # Record the command in a path-neutral form; the interpreter's absolute
    # path is host-specific noise in a shared repo.
    shown = [sanitize(a) if os.path.isabs(a) else a for a in argv]
    lines = [
        "=" * 72,
        title,
        "command: %s" % " ".join(shown),
        "exit code: %d" % res.returncode,
        "=" * 72,
        sanitize(res.stdout).rstrip(),
    ]
    if res.stderr.strip():
        lines += ["", "--- stderr ---", sanitize(res.stderr).rstrip()]
    lines += ["", "VERDICT: %s" % ("PASS (exit 0)" if res.returncode == 0
                                   else "FAIL (exit %d)" % res.returncode), ""]
    outfile.write("\n".join(lines) + "\n")


py = VENV_PY if os.path.exists(VENV_PY) else sys.executable

# 1. structural verification
vf = EVID / ("verification-%s.txt" % DATE)
r = run([py, str(EVID / "verify_briefing_1012.py")])
with open(vf, "w") as fh:
    banner("STEP 1 — structural verification of the delivered artifacts",
           [py, "verify_briefing_1012.py"], r, fh)
print("wrote %s (exit %d)" % (vf.name, r.returncode))

# 2. test suite
tf = EVID / ("test-results-%s.txt" % DATE)
r2 = run([sys.executable, str(REPO / "tests" / "run_briefing_tests.py")],
         cwd=str(REPO))
with open(tf, "w") as fh:
    banner("STEP 2 — briefing verification test suite (dependency-free runner)",
           [sys.executable, "tests/run_briefing_tests.py"], r2, fh)
print("wrote %s (exit %d)" % (tf.name, r2.returncode))

# 3. live URL check
uf = EVID / ("url-check-%s.txt" % DATE)
r3 = run([py, str(EVID / "check_urls_1012.py")], timeout=600)
with open(uf, "w") as fh:
    banner("STEP 3 — live HTTP check of every source URL", [py, "check_urls_1012.py"],
           r3, fh)
print("wrote %s (exit %d)" % (uf.name, r3.returncode))

# 4. claim -> source mapping (machine-readable)
md = BASE.with_suffix(".md").read_text(encoding="utf-8")
srcmap = EVID / ("claim-sources-%s.tsv" % DATE)
rows = [("claim_anchor", "source_url")]

# Bulleted claims carry their sources inline.
for line in md.split("\n"):
    s = line.strip()
    if not s.startswith("- **"):
        continue
    claim = re.sub(r"The user has provided.*", "", s)
    claim = re.sub(r"^\-\s*\*\*", "", claim).split("**")[0].strip()
    urls = re.findall(r"(https?://[^\s)]+)", s)
    for u in urls:
        rows.append((claim[:90], u))

# Section prose (the headline story) cites its sources on following bare-URL
# lines. Attach each to the section heading that precedes it, or the map is a
# partial picture presented as complete.
current = ""
for line in md.split("\n"):
    s = line.strip()
    if s.startswith("## "):
        current = s[3:].strip()
        continue
    if s.startswith("http"):
        rows.append(("section: %s" % current[:80], s))

# de-duplicate while preserving order
seen = set()
uniq = []
for c, u in rows:
    if c == "claim_anchor" or (c, u) not in seen:
        seen.add((c, u))
        uniq.append((c, u))
rows = uniq

with open(srcmap, "w") as fh:
    fh.write("# claim -> source URL map for the %s briefing\n" % DATE)
    fh.write("# one row per (claim, source); regenerated by capture_evidence_1012.py\n")
    for c, u in rows:
        fh.write("%s\t%s\n" % (c, u))
print("wrote %s (%d claim/source rows)" % (srcmap.name, len(rows) - 1))

print()
print("all four evidence files written to", EVID)
sys.exit(0 if all(r.returncode == 0 for r in (r, r2)) else 1)
