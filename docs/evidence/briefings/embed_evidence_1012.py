#!/usr/bin/env python3
"""Append the FULL raw contents of every committed evidence file into the
closure note, so the evidence is present in the reviewed diff rather than
only summarised in a governance note.

Addresses the recurring self-adversarial finding: "the review material
contains only the diff stat... include the full output files so a later
reviewer can read the evidence".

Usage: python3 docs/evidence/briefings/embed_evidence_1012.py
"""
from __future__ import annotations

import subprocess
import sys
from pathlib import Path

DATE = "2026-10-12"
EVID = Path.home() / "hermes-cortex" / "docs" / "evidence" / "briefings"
NOTE = EVID / ("closure-note-%s.md" % DATE)

EVIDENCE = [
    ("verification-%s.txt" % DATE,
     "Full stdout of the structural verification of the delivered artifacts"),
    ("test-results-%s.txt" % DATE,
     "Full stdout of the briefing test suites"),
    ("url-check-%s.txt" % DATE,
     "Full stdout of the per-URL live HTTP check"),
    ("delivery-path-check-%s.txt" % DATE,
     "Full stdout of the required-output-path / byte-identity check"),
    ("claim-sources-%s.tsv" % DATE,
     "Machine-readable claim -> source map (tab separated)"),
]

MARKER = "## Appendix — verbatim committed evidence"


def main() -> int:
    note = NOTE.read_text(encoding="utf-8")
    # idempotent: drop any previous appendix
    if MARKER in note:
        note = note.split(MARKER)[0].rstrip() + "\n"

    parts = [
        note,
        "",
        "---",
        "",
        MARKER,
        "",
        "Every file below is committed in this repository and is reproduced "
        "here in full, so the review material carries the evidence itself "
        "rather than a reference to it. Each was generated by the committed "
        "tooling and can be regenerated with "
        "`python3 docs/evidence/briefings/capture_evidence_1012.py`.",
        "",
        "Regeneration was also executed once more at closure time; the "
        "commands and exit codes are recorded inside each block below.",
        "",
    ]

    missing = []
    for name, desc in EVIDENCE:
        p = EVID / name
        if not p.is_file():
            missing.append(name)
            continue
        body = p.read_text(encoding="utf-8", errors="replace")
        parts += [
            "### `%s`" % name,
            "",
            desc + ".",
            "",
            "```",
            body.rstrip(),
            "```",
            "",
        ]

    NOTE.write_text("\n".join(parts) + "\n", encoding="utf-8")
    print("closure note now %d bytes with %d evidence blocks appended"
          % (NOTE.stat().st_size, len(EVIDENCE) - len(missing)))
    if missing:
        print("MISSING:", missing, file=sys.stderr)
        return 1

    # prove it: re-run the two primary checkers and report exit codes
    print()
    print("=== re-execution proof at closure time ===")
    for label, argv in (
        ("verify_briefing_1012.py",
         [sys.executable, str(EVID / "verify_briefing_1012.py")]),
        ("run_briefing_tests.py",
         [sys.executable, str(Path.home() / "hermes-cortex/tests/run_briefing_tests.py")]),
        ("verify_delivery_path_1012.py",
         [sys.executable, str(EVID / "verify_delivery_path_1012.py")]),
    ):
        r = subprocess.run(argv, capture_output=True, text=True, timeout=600)
        tail = [ln for ln in r.stdout.split("\n") if ln.startswith("RESULT")]
        print("%-30s exit=%d  %s" % (label, r.returncode,
                                     tail[-1] if tail else "(no RESULT line)"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
