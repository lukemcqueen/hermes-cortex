#!/usr/bin/env bash
# Gate transcript for the 2026-10-18 soul-refinement run's close review.
#
# Regenerate (the committed .txt is this script's stdout, nothing retyped):
#   bash docs/evidence/generate-soul-refinement-gates.sh > docs/evidence/soul-refinement-gates-2026-10-18.txt
#
# READ-ONLY: it runs the checks and prints them; it never repairs or regenerates the
# artifact it inspects (the window capture is COMPARED, not rewritten). Every command is
# printed beside its OWN exit code, captured unpiped so no pipe can report for it.
set -uo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
cd "$REPO" || exit 1
norm() { sed -e "s|$HOME|~|g"; }

echo "# Gate transcript — soul-refinement run 2026-10-18"
echo "# Generated by docs/evidence/generate-soul-refinement-gates.sh (read-only)."
echo "# Answers ADV-12788-1 and ADV-12788-2: gate results are CAPTURED here instead of"
echo "# asserted in a close note. Each command prints beside its own exit code."
echo

echo "== 1. Behavioural test: tests/test_stalled_rebase_abort.py (ADV-12788-1) =="
test_out="$(python3 tests/test_stalled_rebase_abort.py 2>&1)"; test_rc=$?
printf '%s\n' "$test_out" | norm
echo "   -> rc=${test_rc}"
echo "   case lines: $(printf '%s\n' "$test_out" | grep -c '  PASS') PASS, $(printf '%s\n' "$test_out" | grep -c '  FAIL') FAIL"
echo

echo "== 2. The REBASE_LIB seam resolves because os is imported (ADV-12788-1) =="
imports="$(grep -n '^import os$' tests/test_stalled_rebase_abort.py)"; import_rc=$?
echo "   grep -n '^import os\$' tests/test_stalled_rebase_abort.py -> ${imports:-<absent>}  (rc=${import_rc})"
grep -n 'REBASE_LIB' tests/test_stalled_rebase_abort.py | head -2 | norm
echo

echo "== 3. No host paths or chat ids in the committed captures (the repo is public) =="
leak="$(grep -c -e "$HOME" -e "1270130526" docs/evidence/soul-refinement-window-2026-10-18.txt docs/evidence/stalled-rebase-failsafe-2026-10-18.txt)"; leak_rc=$?
printf '%s\n' "$leak" | norm
echo "   -> grep rc=${leak_rc} (1 = no match in either file, which is the PASS here)"
echo

echo "== 4. Syntax of the shell files this run changed =="
for f in ops/scripts/lib/git-stalled-rebase.sh \
         ops/scripts/manage/agent-hermes-cortex-sync.sh \
         ops/scripts/agent/agent-ip-submission.sh; do
  bash -n "$f"; printf '   bash -n %s -> rc=%s\n' "$f" "$?"
done
echo

echo "== 5. Adversarial gate (A4) on the scripts this run changed =="
for f in ops/scripts/lib/git-stalled-rebase.sh \
         ops/scripts/manage/agent-hermes-cortex-sync.sh \
         ops/scripts/agent/agent-ip-submission.sh; do
  out="$(python3 "$HOME/.hermes-cortex/scripts/adversarial-verify.py" --file "$f" --level A4 --gate 2>&1)"; rc=$?
  printf '%s\n' "$(printf '%s\n' "$out" | grep -e 'Summary' -e 'GATE_PASSED' -e 'GATE_FAILED')"
  printf '   %s -> rc=%s\n' "$f" "$rc"
done
echo

echo "== 6. The window capture agrees with the job prompt it documents =="
echo "   generator : $(grep -n '^WINDOW_HOURS' docs/evidence/generate-soul-window-evidence.py)"
echo "   committed : $(grep -n 'lookback' docs/evidence/soul-refinement-window-2026-10-18.txt)"
echo -n "   live job  : "
python3 - <<'PY'
import json, os, pathlib
p = pathlib.Path(os.environ.get("HERMES_HOME") or (pathlib.Path.home() / ".hermes")) / "cron" / "jobs.json"
jobs = json.loads(p.read_text())
jobs = jobs.get("jobs", jobs) if isinstance(jobs, dict) else jobs
jobs = list(jobs.values()) if isinstance(jobs, dict) else jobs
j = next((x for x in jobs if x.get("id") == "8449be867645"), {})
prompt = j.get("prompt", "")
print("prompt says LAST 24 HOURS" if "LAST 24 HOURS" in prompt else "!! window phrase NOT found in the live prompt")
PY
echo "   -> the capture's lookback and the prompt must name the same window"
