#!/usr/bin/env python3
"""Read-only capture: the window the 2026-10-18 soul-refinement run mined, and
the rows the session store returned for it.

Regenerate with:
    python3 docs/evidence/generate-soul-window-evidence.py > docs/evidence/soul-refinement-window-2026-10-18.txt

Why this exists: that run's load-bearing result is a NEGATIVE one ("no operator
corrections"), and a negative asserted in prose is an unverified claim. This
capture makes it checkable: the resolved window, every row the store returned in
it with role and timestamp, and the live cron prompt read back from the store.

Read-only: the DB is opened with mode=ro + query_only. No session ids, chat ids
or host paths are printed (the repo is public).
"""
from __future__ import annotations

import datetime
import json
import os
import re
import sqlite3
import sys
from pathlib import Path

KST = datetime.timezone(datetime.timedelta(hours=9))
# The job's live prompt specifies "the LAST 24 HOURS of sessions ending now", so the
# capture uses the SAME window the pass is told to mine: a capture over a different
# lookback cannot evidence what that pass saw.
WINDOW_HOURS = 24
NOW = datetime.datetime.now(KST)
START = NOW - datetime.timedelta(hours=WINDOW_HOURS)

HERMES_HOME = Path(os.environ.get("HERMES_HOME") or (Path.home() / ".hermes"))
STATE_DB = HERMES_HOME / "state.db"
JOBS = HERMES_HOME / "cron" / "jobs.json"
AUDIT = HERMES_HOME / "cron" / "usage_audit.jsonl"
SOUL_JOB = "8449be867645"


def kst(epoch: float) -> str:
    return datetime.datetime.fromtimestamp(epoch, KST).strftime("%Y-%m-%d %H:%M:%S KST")


def scrub(text: str, limit: int = 70) -> str:
    """Redact digit runs (ids/phone-shaped) and collapse whitespace."""
    text = re.sub(r"\d{5,}", "<digits>", text or "")
    text = re.sub(r"\s+", " ", text).strip()
    return text[:limit]


def is_scheduled_prompt(content: str) -> bool:
    """A cron/gateway-scheduled instruction is not an operator correction."""
    head = (content or "").lstrip()
    return head.startswith("[IMPORTANT:") or head.startswith("[Cron delivery:")


def main() -> int:
    print("# Soul-refinement window capture — 2026-10-18")
    print("# Generated by docs/evidence/generate-soul-window-evidence.py (read-only).")
    print("# Everything below is printed by the generator; nothing is retyped by hand.")
    print("#")
    print("# PROVENANCE, and what this file does NOT claim: the window is the one the live")
    print("# job prompt specifies (the last 24 h ending at run time), and the rows are what")
    print("# the session store returned AT GENERATION TIME. A mining pass that ran EARLIER")
    print("# could not have seen a row that arrived after it, so this capture measures the")
    print("# window and its rows — it does not retroactively evidence that pass's result.")
    print("# The pass's own counts are reproducible by re-running this generator, whose")
    print("# window moves with run time; section 3's timestamps are what date each row.")
    print()

    print("== 1. The window this run resolved (run time, NOT the calendar date) ==")
    print(f"   run time           : {NOW.strftime('%Y-%m-%d %H:%M:%S KST')}")
    print(f"   lookback           : {WINDOW_HOURS} h")
    print(f"   window start (KST) : {START.strftime('%Y-%m-%d %H:%M:%S KST')}  epoch={int(START.timestamp())}")
    print(f"   window end   (KST) : {NOW.strftime('%Y-%m-%d %H:%M:%S KST')}  epoch={int(NOW.timestamp())}")
    print(f"   store              : {STATE_DB.name} (opened read-only: mode=ro + PRAGMA query_only)")
    print()

    if not STATE_DB.exists():
        print(f"CANNOT VERIFY: no session store at {STATE_DB.name}")
        return 3

    con = sqlite3.connect(f"file:{STATE_DB}?mode=ro", uri=True)
    con.execute("PRAGMA query_only=1")
    cur = con.cursor()
    lo, hi = START.timestamp(), NOW.timestamp()

    print("== 2. Rows in the window, by role ==")
    for role, n in cur.execute(
        "SELECT role, COUNT(*) FROM messages WHERE timestamp >= ? AND timestamp < ? "
        "GROUP BY role ORDER BY 2 DESC",
        (lo, hi),
    ):
        print(f"   {role:<10} {n}")
    print()

    print("== 3. Every user row in the window (the corrections candidate set) ==")
    rows = list(
        cur.execute(
            "SELECT timestamp, session_id, content FROM messages "
            "WHERE role='user' AND timestamp >= ? AND timestamp < ? ORDER BY timestamp",
            (lo, hi),
        )
    )
    human = 0
    for ts, sid, content in rows:
        scheduled = is_scheduled_prompt(content)
        kind = "scheduled-instruction" if scheduled else "OPERATOR"
        if not scheduled:
            human += 1
        origin = "cron" if str(sid).startswith("cron_") else "non-cron"
        print(f"   [{kst(ts)}] {kind:<21} session={origin:<8} {scrub(content)}")
    print(f"   -> user rows: {len(rows)}   scheduled-instruction: {len(rows) - human}   OPERATOR: {human}")
    print()

    print("== 4. The last non-cron user row before the window (context only) ==")
    for ts, sid, content in cur.execute(
        "SELECT timestamp, session_id, content FROM messages "
        "WHERE role='user' AND timestamp < ? AND session_id NOT LIKE 'cron_%' "
        "ORDER BY timestamp DESC LIMIT 5",
        (lo,),
    ):
        if is_scheduled_prompt(content):
            continue
        origin = "cron" if str(sid).startswith("cron_") else "non-cron"
        print(f"   [{kst(ts)}] session={origin} {scrub(content)}")
        break
    else:
        print("   (none found in the last 5 non-cron user rows)")
    con.close()
    print()

    print("== 5. The live job's prompt, read back from the store AFTER the edit ==")
    if JOBS.exists():
        data = json.loads(JOBS.read_text())
        jobs = data.get("jobs", data) if isinstance(data, dict) else data
        if isinstance(jobs, dict):
            jobs = list(jobs.values())
        job = next((j for j in jobs if j.get("id") == SOUL_JOB), None)
        if job is None:
            print(f"   !! job {SOUL_JOB} not found — readback FAILED")
        else:
            prompt = job.get("prompt", "")
            print(f"   schedule : {job.get('schedule', {}).get('expr')}")
            print(f"   skills   : {job.get('skills')}   enabled: {job.get('enabled')}")
            print(f"   prompt   : {prompt}")
            print(f"   checks   : run-time-window phrase present = {'LAST 24 HOURS' in prompt}"
                  f" | stale 'find today's sessions' gone = {chr(39) + 'find today' + chr(39) not in prompt}")
    else:
        print(f"   CANNOT VERIFY: no jobs store at {JOBS.name}")
    print()

    print("== 6. Late dispatches (why a date-derived window is unsafe) ==")
    if AUDIT.exists():
        total = 0
        after_midnight = []
        for line in AUDIT.read_text().splitlines():
            try:
                d = json.loads(line)
            except ValueError:
                continue
            if d.get("job_id") != SOUL_JOB:
                continue
            total += 1
            t = datetime.datetime.fromisoformat(d["ts"].replace("Z", "+00:00")).astimezone(KST)
            if t.hour < 12:
                after_midnight.append(t.strftime("%Y-%m-%d %H:%M:%S KST"))
        print(f"   logged runs for this job        : {total}")
        print(f"   dispatched AFTER midnight (KST) : {len(after_midnight)}")
        for t in after_midnight:
            print(f"     {t}")
    else:
        print(f"   CANNOT VERIFY: no audit file at {AUDIT.name}")

    print()
    print("== Measured counts (no conclusion asserted) ==")
    print(f"   user rows in the window      : {len(rows)}")
    print(f"   classified scheduled         : {len(rows) - human}")
    print(f"   classified operator          : {human}")
    print(f"   operator rows present at the mining instant (run start {START.strftime('%H:%M')}-{NOW.strftime('%H:%M')} KST): see the timestamps in section 3")
    print("   NOTE: an operator row that ARRIVES after this pass cannot appear in the pass's own result;")
    print("         section 3's timestamps are what distinguishes 'the window was empty then' from 'the store is empty now'.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
