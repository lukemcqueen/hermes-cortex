#!/usr/bin/env bash
# Evidence generator for the stalled-rebase fail-safe (2026-10-18).
#
# Re-run it to regenerate the committed capture:
#   bash docs/evidence/generate-stalled-rebase-evidence.sh > docs/evidence/stalled-rebase-failsafe-2026-10-18.txt
#
# Read-only apart from the throwaway repos the test builds under TMPDIR. Every
# command is printed beside its own exit code, and $HOME is normalised to ~ at the
# generator (never in a hand-edited copy afterwards).
set -uo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
cd "$REPO" || exit 1
norm() { sed -e "s|$HOME|~|g"; }
say() { printf '\n== %s ==\n' "$*"; }

echo "# Stalled-rebase fail-safe — measured capture"
echo "# Generated by docs/evidence/generate-stalled-rebase-evidence.sh"
echo "# Host: fleet Linux agent host · KST · repo revision: $(git rev-parse --short HEAD 2>/dev/null)"
echo "#"
echo "# WHAT THIS MEASURES: the defect (an interrupted 'git pull --rebase' leaves the"
echo "# repository stopped mid-rebase and every commit/push refused) and the fix"
echo "# (ops/scripts/lib/git-stalled-rebase.sh, called from the two pull failure paths)."
echo "# The DEFECT half is re-runnable: tests/test_stalled_rebase_abort.py constructs the"
echo "# stopped-rebase state and asserts a commit is refused BEFORE the helper runs."

say "1. Syntax of every changed shell file (bash -n)"
for f in ops/scripts/lib/git-stalled-rebase.sh \
         ops/scripts/manage/agent-hermes-cortex-sync.sh \
         ops/scripts/agent/agent-ip-submission.sh \
         ops/scripts/cortex-update.sh; do
  bash -n "$f"; printf '   bash -n %s -> rc=%s\n' "$f" "$?"
done

say "2. Behavioural test — builds the stalled state, proves it blocks, then fixes it"
python3 tests/test_stalled_rebase_abort.py 2>&1 | norm
printf '   tests/test_stalled_rebase_abort.py -> rc=%s\n' "${PIPESTATUS[0]}"

say "3. Adversarial gate (A4) on the changed scripts"
for f in ops/scripts/lib/git-stalled-rebase.sh \
         ops/scripts/manage/agent-hermes-cortex-sync.sh \
         ops/scripts/agent/agent-ip-submission.sh; do
  out="$(python3 "$HOME/.hermes-cortex/scripts/adversarial-verify.py" --file "$f" --level A4 --gate 2>&1)"
  rc=$?
  printf '   %s\n' "$(printf '%s\n' "$out" | grep -e 'Summary' -e 'GATE_PASSED' -e 'GATE_FAILED' | norm)"
  printf '   %s -> rc=%s\n' "$f" "$rc"
done

say "4. The failure path in the sync script now clears a stopped rebase"
grep -n -A3 'PULL_OUTPUT=\$(GIT_EDITOR' ops/scripts/manage/agent-hermes-cortex-sync.sh | norm

say "5. Live-state marker: the repo this fix protects is rebase-free at capture time"
printf '   rebase in progress: '
if [ -d "$(git rev-parse --absolute-git-dir)/rebase-merge" ] || [ -d "$(git rev-parse --absolute-git-dir)/rebase-apply" ]; then
  echo "YES (unexpected at capture time)"
else
  echo "no"
fi
printf '   unmerged paths: %s\n' "$(git diff --name-only --diff-filter=U | wc -l)"
