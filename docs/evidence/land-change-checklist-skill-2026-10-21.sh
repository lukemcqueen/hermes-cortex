#!/usr/bin/env bash
# Land the stranded change-checklist skill into the repo source — before/after proof.
#
# WHAT THIS PROVES, and HOW (each claim carries its own raw output):
#   1. BEFORE — the deployed copy differed from the repo copy at the pinned revision.
#      Shown as: both sha256s, both line counts, AND the full unified diff, so the
#      stranded content is readable in this transcript rather than asserted.
#   2. AFTER — the repo copy is byte-identical to the deployed copy.
#      Shown as: both sha256s and `cmp`'s verdict. Byte-identity is what "landed" means;
#      a line-count match would not establish it.
#   3. The repo-only sentence survived, NAMED and LOCATED by line number in both copies.
#
# The proof is CONTENT-based (sha256 + cmp + diff), so it does not depend on mtimes and
# a fresh checkout cannot satisfy it.
#
# WHAT IT DELIBERATELY DOES NOT CLAIM: the parity artifact's totals are NOT used as the
# before/after. The artifact arrived already stale vs the live tree (it recorded 17
# stranded in place; the last committed version recorded 0, which predates this drift),
# so a committed-vs-working comparison of its numbers would attribute a pre-existing
# drift to this change. Only its MEMBERSHIP of change-checklist/SKILL.md is cited, which
# this change does control.
#
# Re-run: bash docs/evidence/land-change-checklist-skill-2026-10-21.sh
set -uo pipefail

REPO="${REPO:-$HOME/hermes-cortex}"
DEPLOYED="${DEPLOYED:-$HOME/.hermes-cortex/skills}"
REL="software-development/change-checklist/SKILL.md"
# The tip this change sat on before the landing — an immutable revision, not "HEAD".
BEFORE="234cb2fc"
OUT="$REPO/docs/evidence/land-change-checklist-skill-2026-10-21.txt"

exec >"$OUT" 2>&1
cd "$REPO" || { echo "FATAL: repo not found at $REPO"; exit 2; }

say() { echo; echo "===== $* ====="; }
# Portable digest: `shasum -a 256` and `sha256sum` are not both present on Linux and BSD,
# so compute it with the interpreter this script already needs.
sha() { python3 -c 'import hashlib,sys; print(hashlib.sha256(open(sys.argv[1],"rb").read()).hexdigest())' "$1"; }

say "0. provenance"
echo "generated-by: this script writes this transcript itself (exec > OUT), so 'generated-by' is a fact about the file"
echo "captured-at:  the working tree this ran on — a committed transcript is always one commit AHEAD of the revision it prints"
echo "before pin:   $BEFORE  (the tip this change sat on before the landing)"

say "1. BEFORE — repo copy at $BEFORE vs the deployed copy"
git show "$BEFORE:skills/$REL" > /tmp/cc_before.md 2>/dev/null
if [ ! -s /tmp/cc_before.md ]; then
  echo "COULD NOT READ $BEFORE:skills/$REL — nothing claimed below"
  echo "GENERATOR_rc=2"
  exit 2
fi
echo "sha256 repo@$BEFORE: $(sha /tmp/cc_before.md)"
echo "sha256 deployed:      $(sha "$DEPLOYED/$REL")"
echo "line counts: repo@$BEFORE=$(wc -l < /tmp/cc_before.md)   deployed=$(wc -l < "$DEPLOYED/$REL")"
diff -u -L "repo@$BEFORE:$REL" -L "deployed:$REL" /tmp/cc_before.md "$DEPLOYED/$REL" > /tmp/cc_diff.txt 2>&1
echo "unified diff lines: $(wc -l < /tmp/cc_diff.txt)   (diff's own rc is expected non-zero here: they differ)"
echo "--- the stranded content, verbatim ---"
cat /tmp/cc_diff.txt
echo "--- end of diff ---"

say "2. AFTER — repo copy NOW vs the deployed copy"
echo "sha256 repo now: $(sha "skills/$REL")"
echo "sha256 deployed: $(sha "$DEPLOYED/$REL")"
if cmp -s "skills/$REL" "$DEPLOYED/$REL"; then
  echo "cmp verdict: IDENTICAL — the landing is a true sync, byte for byte"
else
  echo "cmp verdict: DIFFER — NOT landed"
fi
echo "diff -q output follows (empty = identical):"
diff -q "skills/$REL" "$DEPLOYED/$REL" || true
echo "--- end of diff -q ---"

say "3. the repo-only sentence, named and located"
echo "the sentence is: 'Redirect the store to a temp dir and assert what the tool wrote THERE'"
echo "in the repo copy:"
grep -n 'Redirect the store to a temp dir' "skills/$REL" || echo "  NOT FOUND — the sentence did NOT survive"
echo "in the deployed copy:"
grep -n 'Redirect the store to a temp dir' "$DEPLOYED/$REL" || echo "  NOT FOUND"

say "4. the parity artifact no longer lists change-checklist/SKILL.md as stranded"
echo "occurrences in the refreshed artifact: $(grep -c 'change-checklist/SKILL.md' docs/evidence/skill-drift-parity.txt)"
echo "  (0 = resolved; the artifact itself is regenerated by ops/scripts/manage/check-skill-drift-parity.py)"

say "5. the reconcile report's view of this skill"
python3 ops/scripts/manage/reconcile-stranded-skills.py 2>&1 | grep -A2 'change-checklist' \
  || echo "  (change-checklist no longer appears in the reconcile report — nothing left to land for it)"

say "6. end of transcript"
echo "GENERATOR_rc=0"
