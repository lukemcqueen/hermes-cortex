#!/usr/bin/env bash
# Prove the RUNNING loop-governance MCP server holds the DEPLOYED revision (deploy != load).
#
# Deploying a file says nothing about the process serving it: a long-lived MCP child keeps
# the revision it loaded at startup. The discriminator is TIME — the process's start must be
# at or after the deployed file's mtime — plus CONTENT parity between repo source and the
# deployed copy (so "the file on disk" and "the file the daemon was started from" agree).
#
# Read-only. Linux `ps -o etimes=` is used for the start time; on macOS use
# `ps -o lstart= -p <pid>` and compare by hand.
#
# Usage: bash docs/evidence/mcp-reload-live-verify.sh [repo-path]
set -uo pipefail

REPO="${1:-$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)}"
MANIFEST="${HOME}/.hermes-cortex/deploy-manifest.tsv"
SRC_REL="mcp-servers/loop-gov-mcp.py"
FAILED=0
norm() { sed -e "s|$HOME|~|g"; }

echo "repo: $REPO" | norm
echo "deploy manifest: $MANIFEST" | norm

DEST="$(awk -v k="$SRC_REL" -F'\t' '$1==k {print $2}' "$MANIFEST" 2>/dev/null | head -1)"
if [ -z "$DEST" ]; then
  echo "FAIL: no deploy-map entry for $SRC_REL — refusing to guess the deployed path"
  exit 1
fi
echo "deployed copy: $DEST" | norm
echo

echo "--- 1. repo source == deployed copy (deploy banner stripped on both sides)"
python3 - "$REPO/$SRC_REL" "$DEST" <<'PY'
import sys
from pathlib import Path
repo, dest = Path(sys.argv[1]), Path(sys.argv[2])
if not dest.exists():
    print(f"MISSING deployed copy: {dest}")
    sys.exit(1)


def body(p):
    out = [l for l in p.read_text(encoding="utf-8", errors="replace").splitlines()
           if not l.startswith("# SOURCE:") and "Do NOT edit this file" not in l]
    while out and not out[0].strip():
        out.pop(0)
    return [l for l in out if l.strip()]


same = body(repo) == body(dest)
print(f"identical modulo the deploy banner: {same}")
sys.exit(0 if same else 1)
PY
rc=$?; echo "rc=$rc"; [ "$rc" -eq 0 ] || FAILED=$((FAILED + 1)); echo

echo "--- 2. the deployed file carries the release-path closer"
grep -c "def _close_cycle_unscored(" "$DEST" | norm
if grep -q "def _close_cycle_unscored(" "$DEST"; then
  echo "PRESENT in the deployed copy"
else
  echo "ABSENT from the deployed copy"; FAILED=$((FAILED + 1))
fi
echo

echo "--- 3. the RUNNING MCP server started AFTER that revision was written"
MCP_PIDS="$(pgrep -f "loop-gov-mcp.py" | tr '\n' ' ')"
if [ -z "${MCP_PIDS// /}" ]; then
  echo "FAIL: no running loop-governance MCP process found — nothing to verify"
  FAILED=$((FAILED + 1))
else
  DEP_MTIME="$(stat -c %Y "$DEST")"
  echo "deployed file mtime : $DEP_MTIME ($(date -d "@$DEP_MTIME" '+%F %T %Z'))"
  for pid in $MCP_PIDS; do
    et="$(ps -o etimes= -p "$pid" | tr -d ' ')"
    [ -n "$et" ] || { echo "PID $pid: could not read etimes"; FAILED=$((FAILED + 1)); continue; }
    START=$(( $(date +%s) - et ))
    printf 'pid %s started: %s (%s), etime=%ss\n' \
      "$pid" "$START" "$(date -d "@$START" '+%F %T %Z')" "$et" | norm
    if [ "$START" -ge "$DEP_MTIME" ]; then
      echo "PASS  pid $pid started at/after the deployed revision — this process loaded it"
    else
      echo "FAIL  pid $pid started BEFORE the deployed revision — it holds the OLD code"
      FAILED=$((FAILED + 1))
    fi
  done
fi
echo

echo "--- 4. git state (informational)"
git -C "$REPO" rev-parse HEAD origin/main | norm
echo

echo "=== VERDICT ==="
echo "failed checks: $FAILED"
[ "$FAILED" -eq 0 ] && echo "LIVE SERVER HOLDS THE DEPLOYED REVISION (rc=0)" \
                    || echo "FAILED (rc=$FAILED)"
exit "$([ "$FAILED" -eq 0 ] && echo 0 || echo 1)"
