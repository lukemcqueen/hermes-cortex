#!/usr/bin/env bash
# Deploy-side evidence for the release-path change: deployed copy == repo source, the
# deployed copy carries the new code, and the host's doctor is clean.
#
# What this CANNOT show, and says so: whether the RUNNING MCP daemon has loaded the new
# module. Deploy is not load, so the gateway restart stays an operator action.
#
# Read-only. Resolves the deployed target from the deploy manifest — never a guessed path.
#
# Usage: bash docs/evidence/release-closes-cycle-deploy-verify.sh [repo-path]
set -uo pipefail

REPO="${1:-$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)}"
MANIFEST="${HOME}/.hermes-cortex/deploy-manifest.tsv"
SRC_REL="mcp-servers/loop-gov-mcp.py"

FAILED=0
norm() { sed -e "s|$HOME|~|g"; }
report() { printf '%s\n' "$1" | norm; }

echo "repo: $REPO" | norm
echo "deploy manifest: $MANIFEST" | norm
echo "SELF-INFLICTED WARNING: this capture is written before it is committed, so the doctor"
echo "  run below carries 'Repo clean — N uncommitted change(s)' — that is THIS artifact."
echo "  Disclosed rather than hidden: re-capturing would only move the same warning along."

DEST="$(awk -v k="$SRC_REL" -F'\t' '$1==k {print $2}' "$MANIFEST" 2>/dev/null | head -1)"
if [ -z "$DEST" ]; then
  echo "FAIL: no deploy-map entry for $SRC_REL — refusing to guess the deployed path"
  exit 1
fi
report "deployed target (from the manifest): $DEST"
echo

echo "--- 1. deployed copy matches repo source (deploy banner stripped on both sides)"
python3 - "$REPO/$SRC_REL" "$DEST" <<'PY'
import sys
from pathlib import Path
repo, dest = Path(sys.argv[1]), Path(sys.argv[2])
if not dest.exists():
    print(f"MISSING deployed copy: {dest}")
    sys.exit(1)


def body(p):
    lines = p.read_text(encoding="utf-8", errors="replace").splitlines()
    out = [ln for ln in lines if not ln.startswith("# SOURCE:") and "Do NOT edit this file" not in ln]
    while out and not out[0].strip():
        out.pop(0)
    return [ln for ln in out if ln.strip()]


a, b = body(repo), body(dest)
same = a == b
print(f"repo   lines: {len(a)}")
print(f"deployed lines: {len(b)}")
print(f"identical modulo the deploy banner: {same}")
if not same:
    for i, (x, y) in enumerate(zip(a, b)):
        if x != y:
            print(f"first difference at line {i + 1}:")
            print(f"  repo    : {x}")
            print(f"  deployed: {y}")
            break
    sys.exit(1)
PY
rc=$?; echo "rc=$rc"; [ "$rc" -eq 0 ] || FAILED=$((FAILED + 1)); echo

echo "--- 2. the DEPLOYED file carries the new code (deploy != load, see the note below)"
if grep -q "def _close_cycle_unscored(" "$DEST"; then
  echo "PRESENT  def _close_cycle_unscored( in the deployed copy"
else
  echo "ABSENT   def _close_cycle_unscored( in the deployed copy"
  FAILED=$((FAILED + 1))
fi
echo "NOTE: this host must restart its gateway for the RUNNING MCP daemon to load this"
echo "      module; until then the live close still runs the old revision. Deploy is not"
echo "      load, and no restart was performed by this script."
echo

echo "--- 3. doctor (warnings listed verbatim; failures are the verdict, not the exit code)"
out="$(python3 "$REPO/ops/scripts/manage/cortex-doctor.py" 2>&1)"; rc=$?
printf '%s\n' "$out" | grep -E "^ *⚠️|^ *❌|Overall" | norm || true
echo "doctor rc=$rc"
echo "NOTE: this doctor exits NON-ZERO for warnings alone (its own convention), so the rc is"
echo "      not the verdict here — the fail COUNT is. The verdict is asserted below."
if printf '%s\n' "$out" | grep -qE "Overall: .*0 fail"; then
  echo "PASS  doctor reports 0 failures — every FAIL blocks the push; warnings are disclosed above"
else
  echo "FAIL  doctor reports a failure"
  FAILED=$((FAILED + 1))
fi
echo

echo "--- 4. git state (informational)"
git -C "$REPO" rev-parse HEAD | norm
git -C "$REPO" rev-parse origin/main | norm
git -C "$REPO" rev-list --left-right --count origin/main...HEAD | norm
echo

echo "=== VERDICT ==="
echo "failed checks: $FAILED"
[ "$FAILED" -eq 0 ] && echo "DEPLOY SIDE VERIFIED (rc=0)" || echo "FAILED (rc=$FAILED)"
exit "$([ "$FAILED" -eq 0 ] && echo 0 || echo 1)"
