#!/usr/bin/env bash
# Evidence for the stranded-skill reconciliation (commit 1a0646d5).
#
# READ-ONLY: it never regenerates the parity artifact it reads (that artifact IS the
# measurement — a capture that repairs it cannot report it), and it runs the doctor
# without --fix. Every claim in the cycle note is produced here, each command beside its
# own rc, host paths normalised to ~ at the generator.
#
# Usage: bash docs/evidence/stranded-skills-reconcile-verify.sh [repo-path] [pre-rev]
set -uo pipefail

REPO="${1:-$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)}"
# The last committed parity artifact BEFORE this reconciliation. Pinned as a revision:
# "HEAD" or "the working tree" would be unrepeatable once the change landed.
PREV="${2:-6a243890}"
PARITY_REL="docs/evidence/skill-drift-parity.txt"
SKILLS="skills/devops/enforcement-change-safety/SKILL.md
skills/software-development/change-checklist/SKILL.md
skills/software-development/reflexion-check/SKILL.md"
FAILED=0
norm() { sed -e "s|$HOME|~|g"; }

echo "repo: $REPO" | norm
echo "before-revision for the parity comparison: $PREV"
echo

echo "--- 1. BEFORE: the committed parity artifact at $PREV"
echo "\$ git show $PREV:$PARITY_REL"
git -C "$REPO" show "$PREV:$PARITY_REL" 2>&1 | grep -E "Deployed-only|Files in sync|Verdict" | norm
rc=$?; echo "rc=$rc"; [ "$rc" -eq 0 ] || FAILED=$((FAILED + 1)); echo

echo "--- 2. AFTER: the committed parity artifact at HEAD (read, never regenerated)"
echo "\$ cat $(pwd | norm)/$PARITY_REL"
grep -E "Deployed-only|Files in sync|Verdict" "$REPO/$PARITY_REL" | norm
rc=$?; echo "rc=$rc"; [ "$rc" -eq 0 ] || FAILED=$((FAILED + 1)); echo

echo "--- 3. the three applied skills: repo copy == deployed copy (deploy banner stripped)"
python3 - "$REPO" $SKILLS <<'PY'
import hashlib
import sys
from pathlib import Path

repo = Path(sys.argv[1])
home = Path.home()
bad = 0
for rel in sys.argv[2:]:
    r = repo / rel
    d = home / ".hermes" / rel
    if not (r.exists() and d.exists()):
        print(f"MISSING repo={r.exists()} deployed={d.exists()}  {rel}")
        bad += 1
        continue

    def body(p):
        lines = [l for l in p.read_text(encoding="utf-8", errors="replace").splitlines()
                 if not l.startswith("# SOURCE:") and "Do NOT edit this file" not in l]
        while lines and not lines[0].strip():
            lines.pop(0)
        return "\n".join(l for l in lines if l.strip())

    a, b = body(r), body(d)
    ha = hashlib.sha256(a.encode()).hexdigest()[:16]
    hb = hashlib.sha256(b.encode()).hexdigest()[:16]
    same = a == b
    print(f"{'MATCH' if same else 'DIFFER'}  {rel}")
    print(f"        normalised sha256  repo={ha}  deployed={hb}  lines={len(a.splitlines())}")
    bad += 0 if same else 1
sys.exit(1 if bad else 0)
PY
rc=$?; echo "rc=$rc"; [ "$rc" -eq 0 ] || FAILED=$((FAILED + 1)); echo

echo "--- 4. doctor (warning lines verbatim; the FAIL COUNT is the verdict, not the rc)"
out="$(python3 "$REPO/ops/scripts/manage/cortex-doctor.py" 2>&1)"; rc=$?
printf '%s\n' "$out" | grep -E "^ *⚠️|^ *❌|Overall" | norm || true
echo "doctor rc=$rc (this doctor exits non-zero for warnings alone)"
if printf '%s\n' "$out" | grep -qE "Overall: .*0 fail"; then
  echo "PASS  doctor reports 0 failures"
else
  echo "FAIL  doctor reports a failure"; FAILED=$((FAILED + 1))
fi
echo

echo "--- 5. push landing"
echo "\$ git rev-parse HEAD origin/main"
git -C "$REPO" rev-parse HEAD origin/main | norm
echo "\$ git branch -r --contains 1a0646d5"
git -C "$REPO" branch -r --contains 1a0646d5 2>&1 | norm
if [ "$(git -C "$REPO" rev-parse HEAD)" = "$(git -C "$REPO" rev-parse origin/main)" ]; then
  echo "PASS  HEAD == origin/main (the reconciliation commit is on the remote)"
else
  echo "FAIL  HEAD != origin/main"; FAILED=$((FAILED + 1))
fi
echo

echo "=== VERDICT ==="
echo "failed checks: $FAILED"
[ "$FAILED" -eq 0 ] && echo "RECONCILIATION VERIFIED (rc=0)" || echo "FAILED (rc=$FAILED)"
exit "$([ "$FAILED" -eq 0 ] && echo 0 || echo 1)"
