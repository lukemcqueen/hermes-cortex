#!/usr/bin/env python3
"""Contract test for the two invariants verify-orch-skill-lifecycle.sh relies on.

The push-time adversarial review flagged (ADV-13796-1, ADV-13796-2) that the
checker asserts two things about OTHER components without a committed test:

  1. the doctor emits >=100 non-empty lines AND at least one per-check verdict
     line, so a crashed/truncated run can be told from a real one;
  2. reconcile-stranded-skills.py prints `stranded: <int>` on its verdict line,
     so the checker can judge the COUNT rather than the verdict word.

This file is that test. Both are asserted against the LIVE components on the
deployed tree, not against a copy — a contract test against a stand-in proves
nothing about the thing that actually runs.

Exit code: 0 = both contracts hold; non-zero names which one broke.
"""
from __future__ import annotations

import os
import re
import subprocess
import sys
from pathlib import Path

REPO = Path(os.environ.get("REPO", Path.home() / "hermes-cortex"))
MANAGE = REPO / "ops" / "scripts" / "manage"

# The checker's threshold, restated here as the CONTRACT: if either side moves,
# this test fails and names it, instead of the checker silently degrading to
# "COULD NOT VERIFY" on every run.
MIN_DOCTOR_LINES = 100
VERDICT_LINE = re.compile(r"^[ \t]*[\u2705\u274c\u26a0\ufe0f\u2796]")
STRANDED_LINE = re.compile(r"stranded:\s*([0-9]+)")
# Live-tree floor: the doctor emits ~500 lines today. The point of this constant
# is not the number, it is that a REAL run is an order of magnitude above the
# checker's 100-line bar — so if the bar was ever tightened toward what a real
# run produces, this fails. Deliberately generous: the claim is "well above the
# bar", not a pinned count that would rot. The measured values are recorded in
# docs/evidence/orch-skill-lifecycle-2026-10-26.txt, regenerated by capture.sh.
LIVE_FLOOR = 200


def fail(msg: str) -> None:
    print(f"FAIL: {msg}")
    sys.exit(1)


def main() -> int:
    doctor = MANAGE / "cortex-doctor.py"
    recon = MANAGE / "reconcile-stranded-skills.py"
    for p in (doctor, recon):
        if not p.is_file():
            fail(f"missing component {p} — the checker's dependency is gone")

    # ---- contract 1: doctor run-evidence --------------------------------
    proc = subprocess.run(
        [sys.executable, str(doctor), "--quiet"],
        cwd=str(REPO), capture_output=True, text=True,
    )
    lines = [ln for ln in proc.stdout.splitlines() if ln.strip()]
    verdicts = [ln for ln in lines if VERDICT_LINE.match(ln)]
    print(f"doctor: rc={proc.returncode} nonempty_lines={len(lines)} "
          f"verdict_lines={len(verdicts)}")
    if len(lines) < MIN_DOCTOR_LINES:
        fail(f"doctor emitted {len(lines)} lines, below the checker's "
             f"{MIN_DOCTOR_LINES}-line run-evidence bar")
    if not verdicts:
        fail("doctor emitted no per-check verdict line, so the checker cannot "
             "tell a real run from a crash")
    if len(lines) < LIVE_FLOOR:
        fail(f"doctor emitted only {len(lines)} lines against the live tree "
             f"(expected >= {LIVE_FLOOR}) — the bar may have been tightened "
             "below what a real run produces")

    # ---- contract 2: reconciler count line ------------------------------
    proc = subprocess.run(
        [sys.executable, str(recon)],
        cwd=str(REPO), capture_output=True, text=True,
    )
    m = STRANDED_LINE.search(proc.stdout)
    if not m:
        fail("reconcile-stranded-skills.py printed no 'stranded: <int>' — the "
             "checker's parser cannot judge the count and would report COULD "
             "NOT VERIFY on every run")
    print(f"reconciler: rc={proc.returncode} stranded={m.group(1)} "
          f"(format present)")

    print("PASS: both contracts hold on the live tree")
    return 0


if __name__ == "__main__":
    sys.exit(main())
