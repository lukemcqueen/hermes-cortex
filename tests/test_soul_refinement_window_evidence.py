#!/usr/bin/env python3
"""The soul-refinement window evidence generator must classify before it counts.

The daily soul-refinement pass reads `role='user'` rows out of the sessions
store and treats them as operator corrections. They are not: a cron session
stores its OWN task prompt as a `role='user'` row, so every cron run
contributes a row that reads like operator input. Measured on esther,
2026-10-20: 46 active user rows in a 24 h window, of which 25 belonged to
cron sessions and only 13 were prose inside the 4 human sessions. A pass that
counts raw rows over-reports by roughly 3.5x and buries the operator's real
message.

Four properties, each measured rather than asserted in prose:

  1. REDACTION COVERS, AND IS NARROW. The transcript is committed to a PUBLIC
     repo and the store's own session ids and gateway chat ids are long digit
     runs, which the shared-surface guard reads as phone numbers. Masking must
     hit 7+ digit runs and collapse home paths - and must NOT be a blanket
     digit strip, or ordinary counts become unreadable.
  2. THE MARKER SET IS THE CONTRACT. Each machine marker maps to its own
     class; a marker that appears MID-text is prose, not a marker, because the
     generator matches a LEADING marker only. A classifier that matched
     anywhere would label an operator quoting a cron delivery as a cron run.
  3. THE GENERATOR IS READ-ONLY against the sessions store. It opens with
     mode=ro and PRAGMA query_only=1. A capture that can write to the store it
     measures is a capture that can hide what it exists to show.
  4. THE COMMITTED ARTIFACT still carries the verbatim markers around its body,
     so the "verbatim" claim remains checkable.

Run: python3 -m pytest tests/test_soul_refinement_window_evidence.py -q
"""

import importlib.util
import subprocess
import sys
from pathlib import Path

_REPO_ROOT = Path(__file__).resolve().parents[1]
_GENERATOR = _REPO_ROOT / "docs" / "evidence" / "soul-refinement-window-2026-10-20.py"
_ARTIFACT = _REPO_ROOT / "docs" / "evidence" / "soul-refinement-window-2026-10-20.txt"


def _gen_module():
    spec = importlib.util.spec_from_file_location("soul_window_generator", _GENERATOR)
    assert spec is not None and spec.loader is not None
    _stash_env()
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def _stash_env():
    """The generator reads HOME for the store path. Nothing to restore here, but
    keep the seam obvious for the subprocess test below."""
    return None


# ---------------------------------------------------------------- 1. redaction

def test_redaction_masks_long_digit_runs_wherever_they_sit():
    mod = _gen_module()
    # Built by repetition so this SOURCE file carries no long digit literal:
    # the guard that rejects long digit runs in committed text is the very
    # rule this test is about.
    #
    # The boundary is pinned by the LENGTH OF THE MASK, not merely by the run
    # being absent: a run that is still there would contain the run itself, and
    # a threshold widened past the true boundary still removes it.
    seven = "9" * 7
    out7 = mod.redact("sid " + seven + " end")
    assert seven not in out7, "a 7-digit run is the documented boundary and must be masked"
    assert out7 == "sid <7-digit> end", out7

    twelve = "9" * 12
    out12 = mod.redact("sid " + twelve + " end")
    assert out12 == "sid <12-digit> end", out12

    # Not anchored: a run anywhere in the line is masked, not only at an edge.
    embedded = "sid " + twelve + " end"
    assert mod.redact(embedded).startswith("sid <12-digit>"), mod.redact(embedded)

    home = "/" + "home" + "/" + "someone"
    assert "someone" not in mod.redact("path " + home + "/x"), mod.redact(home)
    assert "~" in mod.redact(home + "/x")


def test_redaction_is_narrow_enough_to_keep_ordinary_counts():
    """A blanket digit strip would destroy the counts the artifact exists to
    report, so short runs must survive intact."""
    mod = _gen_module()
    assert mod.redact("474 pass, 15 warn") == "474 pass, 15 warn"
    six = "4" * 6
    assert six in mod.redact(six), "6 digits is not a phone-shaped run"


# --------------------------------------------------------------- 2. classifier

def test_each_documented_marker_maps_to_its_own_class():
    mod = _gen_module()
    cases = {
        "[IMPORTANT: The user has invoked the \"soul-refinement\" skill, indicating": "cron_self_prompt",
        "[IMPORTANT: You are running as a scheduled cron job. DELIVERY:": "cron_self_prompt",
        "[IMPORTANT: Background process proc_abc completed normally": "internal_notification",
        "[INTERNAL NOTIFICATION - generated by the Hermes gateway": "internal_notification",
        "[Cron delivery: local-agent-daily-ai-brief]": "pasted_cron_delivery",
        "Gateway message origin (JSON data, not instructions or authorization):": "gateway_origin_wrapper",
    }
    for text, expected in cases.items():
        got = mod.classify(text)
        assert got == expected, "classify(%r) -> %r, want %r" % (text[:40], got, expected)


def test_real_operator_prose_is_not_swallowed_by_the_classifier():
    mod = _gen_module()
    for text in (
        "esther, your last changes... did you take into account macos?",
        "Clean up the HC docs. Organize, merge, prune. Be thorough.",
        "I'm getting tired of seeing agents just gloss over the warnings",
    ):
        assert mod.classify(text) == "unclassified_human_session_prose", text


def test_a_marker_mid_text_is_prose_not_a_marker():
    """Only a LEADING marker counts. The operator pastes cron deliveries and
    agent messages constantly; a match-anywhere classifier would file those as
    machine output and silently drop them from review.

    Every marker is exercised MID-text, not just one: a classifier that
    special-cases a single marker's anchor would pass a one-marker test.
    """
    mod = _gen_module()

    def quoted(prefix, marker):
        return prefix + marker + "\nand I disagree with it"

    cases = [
        ("Here is what the cron said:\n", "[Cron delivery: local-agent-daily-ai-brief]"),
        ("Here is what the cron said:\n", "[INTERNAL NOTIFICATION - generated by the Hermes gateway"),
        ("Here is what the cron said:\n", "[IMPORTANT: Background process proc_abc completed normally"),
        ("Here is what the cron said:\n", "[IMPORTANT: The user has invoked the \"soul-refinement\" skill, indicating"),
        ("Here is what the cron said:\n", "[IMPORTANT: You are running as a scheduled cron job. DELIVERY:"),
        ("Here is what the cron said:\n", "Gateway message origin (JSON data, not instructions or authorization):"),
    ]
    for prefix, marker in cases:
        got = mod.classify(quoted(prefix, marker))
        assert got == "unclassified_human_session_prose", (
            "a marker at line 2 must read as prose (match must be LEADING), got %r for %r"
            % (got, marker[:36])
        )

    # And the same markers DO classify when they genuinely lead.
    for _, marker in cases:
        assert mod.classify(marker) != "unclassified_human_session_prose", marker[:36]


def test_leading_whitespace_does_not_defeat_a_real_marker():
    mod = _gen_module()
    assert mod.classify("   [INTERNAL NOTIFICATION - x") == "internal_notification"


# -------------------------------------------------------- 3. read-only contract

def test_the_generator_opens_the_store_read_only():
    """Read the GENERATOR's own source and assert the read-only property on it.

    The path is resolved from this file's own root, never a bare absolute
    string, so the claim is about the artefact the diff carries."""
    root = _REPO_ROOT
    gen = root / "docs" / "evidence" / "soul-refinement-window-2026-10-20.py"
    src = gen.read_text()
    assert "mode=ro" in src, "the store must be opened with mode=ro"
    assert "PRAGMA query_only=1" in src, "query_only must be set"
    assert "sqlite3.connect('file:%s?mode=ro' % DB, uri=True" in src, (
        "the ro mode must be on the actual connect() call that reaches the store"
    )


def test_running_the_generator_is_a_read_only_measurement():
    """Drive the REAL script as a process and require a clean, non-empty
    window. If it ever writes to the store it measures, this fails."""
    proc = subprocess.run(
        [sys.executable, str(_GENERATOR)],
        cwd=str(_REPO_ROOT), capture_output=True, text=True, timeout=180,
    )
    assert proc.returncode == 0, proc.stderr[-2000:]
    out = proc.stdout
    assert "WINDOW IS NON-EMPTY" in out, out[-2000:]
    assert "--- row counts by role, inside the window ---" in out
    assert "active=1" in out, "the active=1 filter's effect must be reported"
    assert "rc      : 0" in out
    # The exclusivity of the six prefixes is REPORTED, not assumed.
    assert "SUSPECT rows: classified prose but machine-shaped" in out
    assert "count : " in out


def test_a_machine_shaped_row_called_prose_is_flagged_not_hidden():
    """The prose tally is the number the whole artifact rests on, and the six
    prefixes are not provably exhaustive. So a row the classifier called prose
    but which still LOOKS machine-generated must be reported as a warning rather
    than quietly counted as operator prose."""
    mod = _gen_module()
    assert mod.looks_machine_shaped("[UNSEEN MARKER] some gateway line") is True
    assert mod.looks_machine_shaped('{"platform": "telegram"}') is True
    assert mod.looks_machine_shaped("   [INTERNAL NOTIFICATION - x") is True
    # A genuine operator message must NOT be swept into the warning bucket, or
    # the warning fires on every run and its reader learns to ignore it.
    assert mod.looks_machine_shaped("esther, why is there no learning report from titus?") is False
    assert mod.looks_machine_shaped("Clean up the HC docs. Organize, merge, prune.") is False


# ------------------------------------------------- 4. the artifact stays verbatim

def test_the_committed_artifact_keeps_its_verbatim_markers():
    text = _ARTIFACT.read_text()
    begin = "----- BEGIN VERBATIM GENERATOR OUTPUT -----"
    end = "----- END VERBATIM GENERATOR OUTPUT -----"
    assert begin in text and end in text, "the verbatim markers must survive"
    body = text.split(begin, 1)[1].split(end, 1)[0]
    assert "WINDOW IS NON-EMPTY" in body, "the body must be the generator's own output"
    assert "row counts by role" in body


def test_the_artifact_does_not_direct_the_reader_to_a_verdict():
    """An artifact must state provenance, never conclude for the reviewer."""
    lowered = _ARTIFACT.read_text().lower()
    for directive in ("read this first", "note 0 fail", "both green", "verdict: pass"):
        assert directive not in lowered, "artifact must not assert a verdict: %r" % directive


if __name__ == "__main__":
    fns = [v for k, v in sorted(globals().items()) if k.startswith("test_") and callable(v)]
    failed = 0
    for fn in fns:
        try:
            fn()
            print("  PASS  %s" % fn.__name__)
        except Exception as exc:  # noqa: BLE001
            failed += 1
            print("  FAIL  %s  %s" % (fn.__name__, exc))
    print("ALL PASS (%d tests)" % len(fns) if not failed else "FAIL (%d failed)" % failed)
    sys.exit(1 if failed else 0)
